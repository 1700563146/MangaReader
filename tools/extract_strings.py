def replace_in_file(path: pathlib.Path, entries) -> None:
    text = path.read_text(encoding='utf-8')
    for literal, key, formatted in entries:
        if literal not in text:
            print('MISS', path.name, literal)
            continue
        if formatted:
            args = {
                'shelf_unfavorite_count': 'selection.size',
                'history_page': 'it + 1',
                'downloads_running': 'task.done, task.total',
                'downloads_failed': 'task.errorCode.orEmpty()',
                'browse_sources_enabled': 'sources.size',
                'search_count': 'result.items.size',
                'detail_last_chapter': 'comic.lastChapterTitle',
                'detail_download_count': 'state.selectedChapters.size',
                'detail_chapters_count': 'state.chapters.size',
                'local_last_scan': 'root.lastCount',
                'rules_last_error': 'source.lastErrorCode',
            }[key]
            replacement = f'stringResource(R.string.{key}, {args})'
        else:
            replacement = f'stringResource(R.string.{key})'
        text = text.replace(literal, replacement)
    if 'androidx.compose.ui.res.stringResource' not in text:
        text = text.replace(
            'import androidx.compose.ui.Modifier',
            'import androidx.compose.ui.Modifier\nimport androidx.compose.ui.res.stringResource',
            1,
        )
    if 'import io.github.saonte.mangareader.R\n' not in text:
        # 放在第一个 io.github.saonte 导入之前
        m = re.search(r'^import io\.github\.saonte\.', text, re.M)
        if m:
            text = text[: m.start()] + 'import io.github.saonte.mangareader.R\n' + text[m.start():]
        else:
            m2 = re.search(r'^import coil3\.', text, re.M)
            anchor = m2.start() if m2 else text.index('\n\n')
            text = text[:anchor] + 'import io.github.saonte.mangareader.R\n' + text[anchor:]
    path.write_text(text, encoding='utf-8')


def write_strings(path: pathlib.Path, mapping, extra=()):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for name, value in mapping.items():
        escaped = value.replace("'", "\\'")
        lines.append(f'    <string name="{name}">{escaped}</string>')
    lines.append('</resources>')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


